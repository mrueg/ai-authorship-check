import { describe, expect, it } from "vitest";
import { findSignature } from "../src/signatures.js";

describe("findSignature", () => {
  it.each([
    ["🤖 Generated with [Claude Code](https://claude.com/claude-code)", "generated-with footer"],
    ["Fix the thing\n\nGenerated by GitHub Copilot", "generated-with footer"],
    ["Summary\n\nCo-Authored-By: Claude <noreply@anthropic.com>", "co-authored-by AI trailer"],
    ["Co-authored-by: someone <noreply@anthropic.com>", "co-authored-by AI noreply address"],
    ["As an AI language model, I cannot run your code.", "assistant boilerplate"],
    ["<!-- Generated with Cursor -->\nLooks good", "generated-with footer"],
  ])("matches %j", (text, name) => {
    expect(findSignature(text)?.name).toBe(name);
  });

  it.each([
    "I asked Claude about this and it was wrong, so I debugged it myself.",
    "Co-authored-by: Jane Doe <jane@example.com>",
    "The file is generated with protoc, don't edit it by hand.",
    "Copilot suggested this but I rewrote it.",
    "We generated the bindings using bindgen.",
  ])("does not match human text %j", (text) => {
    expect(findSignature(text)).toBeUndefined();
  });
});
