import { describe, expect, it } from "vitest";
import { findSignature } from "../src/signatures.ts";

describe("findSignature", () => {
  it.each([
    ["🤖 Generated with [Claude Code](https://claude.com/claude-code)", "generated-with footer"],
    ["Body\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code) and reviewed by me", "generated-with footer"],
    ["Fix the thing\n\nGenerated by GitHub Copilot", "generated-with footer"],
    ["Details\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_", "generated-with footer"],
    ["Done.\n\nThis PR was generated with Codex (gpt-5).", "generated-with footer"],
    ["<!-- Generated with Cursor -->\nLooks good", "generated-with footer"],
    ["Summary\n\nCo-Authored-By: GitHub Copilot", "co-authored-by AI trailer"],
    ["Summary\n\nCo-Authored-By: Claude <noreply@anthropic.com>", "co-authored-by AI noreply address"],
    ["Co-authored-by: Claude Opus 5.5 <noreply@anthropic.com>", "co-authored-by AI noreply address"],
    ["Co-authored-by: someone <noreply@anthropic.com>", "co-authored-by AI noreply address"],
    ["Co-authored-by: Mona <198982749+Copilot@users.noreply.github.com>", "co-authored-by AI noreply address"],
    ["Co-authored-by: devin-ai-integration[bot] <158243242+devin-ai-integration[bot]@users.noreply.github.com>", "co-authored-by AI noreply address"],
    ["As an AI language model, I cannot run your code.", "assistant boilerplate"],
    ["Great question! As an AI assistant, I'm happy to help.", "assistant boilerplate"],
    // Zero-width characters don't hide a signature.
    ["Body\n\n🤖 Gene\u200Brated with [Clau\u200Dde Code](https://claude.com/claude-code)", "generated-with footer"],
    ["Fix\n\nGenerated by GitHub\u2060 Copilot", "generated-with footer"],
  ])("matches %j", (text, name) => {
    expect(findSignature(text)?.name).toBe(name);
  });

  it.each([
    "I asked Claude about this and it was wrong, so I debugged it myself.",
    "Co-authored-by: Jane Doe <jane@example.com>",
    "The file is generated with protoc, don't edit it by hand.",
    "Copilot suggested this but I rewrote it.",
    "We generated the bindings using bindgen.",
    // People named like tools.
    "Pairing on this one.\n\nCo-authored-by: Devin Smith <devin@example.com>",
    "Co-authored-by: Claude Dupont <claude.dupont@example.fr>",
    "Co-authored-by: Jules <jules@example.org>",
    // Tool names as ordinary words in prose.
    "The scroll event generated by cursor movement fires twice on Linux.",
    // Quoting someone else's AI text is not writing it.
    "> Fixed in #12.\n>\n> 🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nThanks, but this breaks Windows.",
    'The bot replied "As an AI language model I cannot help", which is useless.',
    "Our template says:\n```\nGenerated by GitHub Copilot\n```\nshould we drop that line?",
    "Don't paste `Co-authored-by: Claude <noreply@anthropic.com>` into commits here.",
    // Mentions of a trailer in prose, user stories, look-alike logins and names.
    "Please drop the Co-authored-by: Claude <noreply@anthropic.com> line from your commit.",
    "As an AI assistant, I want to read files so that I can summarize them.",
    "User story: as an AI assistant I need access to the repo.",
    "Co-authored-by: Pat <12345+aviation-copilot@users.noreply.github.com>",
    "Co-authored-by: codex-team <team@example.com>",
    // Code inside a longer fence, or after a fence-like line inside a block, is still code.
    "````\n```\nGenerated by GitHub Copilot\n````\nreal text",
    "```\nfoo\n```python\nGenerated by GitHub Copilot\n```\nreal text",
  ])("does not match human text %j", (text) => {
    expect(findSignature(text)).toBeUndefined();
  });

  it("stays fast on long, adversarial bodies", () => {
    const bodies = [
      " ".repeat(65_000),
      "\n".repeat(65_000),
      "- ".repeat(30_000) + "generated by",
      "generated with copilot" + " (x)".repeat(15_000) + " nope",
      "co-authored-by: " + "<".repeat(60_000),
      "co-authored-by: <" + "copilot".repeat(9_000),
      "co-authored-by: copilot" + " ".repeat(60_000) + "<",
      "co-authored-by: copilot" + "\t".repeat(60_000) + "<",
      "co-authored-by: copilot " + "x".repeat(60_000) + " <a",
    ];
    const t0 = Date.now();
    for (const b of bodies) findSignature(b);
    expect(Date.now() - t0).toBeLessThan(500);
  });
});
