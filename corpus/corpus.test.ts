import { describe, expect, it } from "vitest";
import { stripSignature } from "./collect.ts";
import { buildPrompt, cleanOutput } from "./generate.ts";
import { isEnglish, splitFor, type CorpusItem } from "./lib.ts";

describe("stripSignature", () => {
  it("removes the footer, the rule above it and trailing blank lines", () => {
    const body = "Fixes the cache key.\n\nDetails here.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n";
    expect(stripSignature(body)).toBe("Fixes the cache key.\n\nDetails here.");
  });
  it("removes an emoji footer", () => {
    expect(stripSignature("Body text\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)")).toBe("Body text");
  });
  it("leaves text without a signature alone", () => {
    expect(stripSignature("plain text")).toBe("plain text");
  });
});

describe("cleanOutput", () => {
  const long = "The build fails on Windows because the path separator is hard-coded in the loader.";
  it("unwraps code fences and preambles", () => {
    expect(cleanOutput("```markdown\n" + long + "\n```")).toBe(long);
    expect(cleanOutput("Here's the comment:\n\n" + long)).toBe(long);
  });
  it("rejects refusals and too-short output", () => {
    expect(cleanOutput("I can't help with that request, sorry about it, really.")).toBeUndefined();
    expect(cleanOutput("ok")).toBeUndefined();
  });
});

describe("buildPrompt", () => {
  const item = {
    id: "x", label: "human", kind: "issue_comment", origin: "o", created_at: "", repo: "a/b", url: "",
    title: "Crash on start", context: "It crashes.", text: "same here on 2.1", split: "dev",
  } satisfies CorpusItem;
  it("includes the thread for comments and the draft only when rewriting", () => {
    expect(buildPrompt(item, "scratch")).toContain("<post>\nIt crashes.\n</post>");
    expect(buildPrompt(item, "scratch")).not.toContain("same here");
    expect(buildPrompt(item, "rewrite")).toContain("<draft>\nsame here on 2.1\n</draft>");
  });
});

describe("isEnglish", () => {
  it("accepts English and rejects other languages", () => {
    expect(isEnglish("I tried this on the latest version and it is still broken for me, but only on Linux.")).toBe(true);
    expect(isEnglish("Das Problem tritt auf, wenn die Datei nicht existiert und der Pfad leer ist.")).toBe(false);
    expect(isEnglish("在启动时崩溃，日志中没有任何错误信息，请帮忙看看是什么原因导致的问题")).toBe(false);
  });
});

describe("splitFor", () => {
  it("is stable and case-insensitive", () => {
    expect(splitFor("Owner/Repo")).toBe(splitFor("owner/repo"));
  });
});
