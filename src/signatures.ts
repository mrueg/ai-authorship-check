/**
 * Explicit disclosures that a text was produced by an AI tool. A match is
 * treated as certain, so the model is not consulted.
 *
 * Runs on the raw body, before preprocessing, because these markers often live
 * in footers and HTML comments that preprocessing removes.
 *
 * Keep patterns specific: a false match here always gives the AI reaction.
 */

const TOOLS = [
  "claude code",
  "claude",
  "chatgpt",
  "openai codex",
  "codex",
  "github copilot",
  "copilot",
  "cursor",
  "gemini",
  "devin",
  "aider",
  "windsurf",
  "openhands",
  "jules",
  "amp",
  "cline",
  "roo code",
].join("|");

export interface SignaturePattern {
  name: string;
  pattern: RegExp;
}

export const SIGNATURES: SignaturePattern[] = [
  {
    // "🤖 Generated with [Claude Code](https://claude.com/claude-code)", "Generated by Copilot"
    name: "generated-with footer",
    pattern: new RegExp(`(?:🤖\\s*)?generated (?:with|by|using) \\[?(?:${TOOLS})\\b`, "i"),
  },
  {
    // Commit-style trailer pasted into a PR body: "Co-Authored-By: Claude <noreply@anthropic.com>"
    name: "co-authored-by AI trailer",
    pattern: new RegExp(`^\\s*co-authored-by:\\s*(?:${TOOLS})\\b`, "im"),
  },
  {
    name: "co-authored-by AI noreply address",
    pattern: /co-authored-by:[^\n]*<(?:noreply@anthropic\.com|[^>]*copilot[^>]*@users\.noreply\.github\.com|[^>]*cursoragent@cursor\.com)>/i,
  },
  {
    // Chat-assistant boilerplate that only appears when a reply is pasted verbatim.
    name: "assistant boilerplate",
    pattern: /\bas an ai (?:language model|assistant)\b/i,
  },
];

export function findSignature(rawBody: string): SignaturePattern | undefined {
  return SIGNATURES.find((s) => s.pattern.test(rawBody));
}
