/**
 * Explicit disclosures that a text was produced by an AI tool. A match is
 * treated as certain, so the model is not consulted.
 *
 * Matching skips quoted lines, fenced code and inline code (a person quoting
 * an AI reply is not an AI), but keeps HTML comments, because tools often hide
 * their markers there.
 *
 * Keep patterns specific: a false match here always gives the AI reaction.
 * Several tool names are also first names (Claude, Devin, Jules) or ordinary
 * words (cursor, amp), so a tool name alone is never enough.
 */
import { normalizeNewlines, stripFencedCode, stripInvisible, stripQuotes } from "./preprocess.ts";

const TOOLS = [
  "claude code",
  "claude",
  "chatgpt",
  "openai codex",
  "codex",
  "github copilot",
  "copilot",
  "cursor",
  "gemini",
  "devin",
  "aider",
  "windsurf",
  "openhands",
  "jules",
  "amp",
  "cline",
  "roo code",
].join("|");

/** Tool names that are not also people's names or common words. */
const UNAMBIGUOUS_TOOLS = [
  "claude code",
  "chatgpt",
  "openai codex",
  "codex",
  "github copilot",
  "copilot",
  "gemini",
  "windsurf",
  "openhands",
  "roo code",
].join("|");

/**
 * Commit-author addresses that only AI tools use. GitHub noreply addresses are
 * matched exactly (optionally with the numeric "123+" prefix), so a person whose
 * login merely contains "copilot" doesn't match.
 */
const NOREPLY = String.raw`(?:\d+\+)?`;
const AI_ADDRESSES = [
  String.raw`noreply@anthropic\.com`,
  String.raw`cursoragent@cursor\.com`,
  ...["copilot", String.raw`copilot-swe-agent\[bot\]`, String.raw`devin-ai-integration\[bot\]`, String.raw`google-labs-jules\[bot\]`]
    .map((login) => String.raw`${NOREPLY}${login}@users\.noreply\.github\.com`),
].join("|");

export interface SignaturePattern {
  name: string;
  pattern: RegExp;
}

export const SIGNATURES: SignaturePattern[] = [
  {
    // "🤖 Generated with [Claude Code](https://claude.com/claude-code)": the emoji makes it unambiguous.
    name: "generated-with footer",
    pattern: new RegExp(String.raw`🤖[\s*_]*generated (?:with|by|using)\s+\[?(?:${TOOLS})\b`, "i"),
  },
  {
    // A line that is nothing but the footer: "Generated by GitHub Copilot", "_Generated with
    // [Claude Code](…)_", "<!-- Generated with Cursor -->", "This PR was generated with Codex (gpt-5)."
    // In running prose ("events generated by cursor movement") the line has more words.
    name: "generated-with footer",
    pattern: new RegExp(
      // Stays within one line ([ \t], not \s) and avoids adjacent overlapping repeats, so it
      // cannot backtrack badly on long bodies.
      String.raw`^[ \t*_#-]*(?:<!--[ \t]*[*_]*)?` +
        String.raw`(?:this (?:pr|pull request|issue|comment|description|reply|response|summary) (?:was|is) )?` +
        String.raw`generated (?:with|by|using)[ \t]+\[?(?:${TOOLS})\]?(?:\([^)\s]*\))?` +
        String.raw`(?:[ \t]*\([^)\n]*\)|[ \t]+(?:agent|cli|ai|v?\d[\w.-]*))*` +
        String.raw`[ \t*_.!]*(?:-->[ \t]*)?$`,
      "im",
    ),
  },
  {
    // Commit-style trailer pasted into a PR body: "Co-Authored-By: GitHub Copilot". The tool name
    // must be followed by a space, "<" or the end ("codex-team" is not Codex). The trailing
    // whitespace sits inside the optional group so it can't overlap [^<\n]* and backtrack.
    name: "co-authored-by AI trailer",
    pattern: new RegExp(
      String.raw`^[ \t]*co-authored-by:[ \t]*(?:${UNAMBIGUOUS_TOOLS})(?=[ \t<]|$)[^<\n]*(?:<[^>\n]*>[ \t]*)?$`,
      "im",
    ),
  },
  {
    // "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>", as a line of its own: prose that
    // mentions such a trailer ("please drop the Co-authored-by: … line") doesn't count.
    name: "co-authored-by AI noreply address",
    pattern: new RegExp(String.raw`^[ \t]*co-authored-by:[^\n<]*<(?:${AI_ADDRESSES})>[ \t]*$`, "im"),
  },
  {
    // Chat-assistant boilerplate that only appears when a reply is pasted verbatim. Must start a
    // line or sentence, so quoting it ('it replied "As an AI language model …"') does not count,
    // and user stories ("As an AI assistant, I want to …") are excluded.
    name: "assistant boilerplate",
    pattern:
      /(?:^|[.!?]\s+)as an ai (?:language model\b|assistant\b(?!,?[ \t]+i[ \t]+(?:want|need|would like|wish|expect|should)\b))/im,
  },
];

/** The part of the body that counts as the author's: no quotes, fenced or inline code. */
export function signatureText(rawBody: string): string {
  return stripQuotes(stripFencedCode(stripInvisible(normalizeNewlines(rawBody)))).replace(/`[^`\n]*`/g, "");
}

export function findSignature(rawBody: string): SignaturePattern | undefined {
  const text = signatureText(rawBody);
  return SIGNATURES.find((s) => s.pattern.test(text));
}
